/**
 * Regenerates the bundled list of statutory health insurers
 * (`src/lib/organization/personal-details/statutory-health-insurers.ts`, spec #2068)
 * from the GKV-Spitzenverband's Stammdatendatei.
 *
 * 1. Download the current file (public, free, published under §§ 95b, 98a SGB IV;
 *    its terms of use apply: https://download.gkv-ag.de/Content/Stammdatendatei_Nutzungsbedingungen.pdf):
 *    https://stammdatendatei.gkv-ag.de/V300/Stammdatendatei300.zip
 * 2. Unzip it and run: pnpm tsx scripts/update-statutory-health-insurers.ts <ESDD0-GES_V300_YYYYMMDD.XML>
 * 3. Format the result: pnpm exec oxfmt -c ../../.oxfmtrc.json src/lib/organization/personal-details/statutory-health-insurers.ts
 *
 * Every Einzugsstelle of a statutory health insurer (kassenart 14 AOK, 15 BKK,
 * 16 Ersatzkassen, 17 IKK, 18 Knappschaft, 20 LKK) is taken with its Betriebsnummer
 * and its Kurzbezeichnung, verbatim. One the file shows as ended (`gueltig_bis`
 * before the file's day) is kept as removed: records that picked it keep it, new
 * picks refuse it. Insurers on the current list are never dropped: one missing
 * from a newer file stays, removed from that file's day.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { XMLParser } from "fast-xml-parser";
import { Temporal } from "temporal-polyfill";
import { STATUTORY_HEALTH_INSURERS } from "../src/lib/organization/personal-details/statutory-health-insurers";
import type { StatutoryInsurer } from "../src/lib/organization/personal-details/health-insurance";

const STATUTORY_KASSENARTEN = new Set(["14", "15", "16", "17", "18", "20"]);
/** Insurers that ended before this day are left out of a new list (they predate it). */
const EARLIEST_REMOVAL_KEPT = "2020-01-01";
const SOURCE = "https://stammdatendatei.gkv-ag.de/V300/Stammdatendatei300.zip";
const TARGET = resolve(
	import.meta.dirname,
	"../src/lib/organization/personal-details/statutory-health-insurers.ts",
);

type Einzugsstelle = {
	"@_bbnr": string;
	"@_kassenart"?: string;
	"@_gueltig_bis"?: string;
	"@_nachfolge_bn"?: string;
	Adressdaten?: { Kurzbezeichnung?: string };
};

const file = process.argv[2];
if (!file) {
	console.error("Usage: tsx scripts/update-statutory-health-insurers.ts <Stammdatendatei XML>");
	process.exit(1);
}

const parsed = new XMLParser({
	ignoreAttributes: false,
	parseTagValue: false,
	parseAttributeValue: false,
	isArray: (name) => name === "Einzugsstelle",
}).parse(readFileSync(file, "latin1")) as {
	Stammdatendatei: {
		Steuerungsdaten: { Datum_Erstellung: string };
		Einzugsstelle: Einzugsstelle[];
	};
};
const created = parsed.Stammdatendatei.Steuerungsdaten.Datum_Erstellung;
const asOf = Temporal.PlainDateTime.from(created).toPlainDate().toString();

const fromFile = new Map<string, StatutoryInsurer>();
for (const stelle of parsed.Stammdatendatei.Einzugsstelle) {
	if (!STATUTORY_KASSENARTEN.has(stelle["@_kassenart"] ?? "")) continue;
	const name = stelle.Adressdaten?.Kurzbezeichnung?.trim();
	const betriebsnummer = stelle["@_bbnr"];
	if (!name || !/^\d{8}$/.test(betriebsnummer)) continue;
	const endedOn = stelle["@_gueltig_bis"];
	if (endedOn !== undefined && endedOn < asOf) {
		if (endedOn < EARLIEST_REMOVAL_KEPT) continue;
		const removedOn = Temporal.PlainDate.from(endedOn).add({ days: 1 }).toString();
		const successor = stelle["@_nachfolge_bn"];
		fromFile.set(betriebsnummer, {
			name,
			betriebsnummer,
			removedOn,
			...(successor ? { successor } : {}),
		});
	} else {
		fromFile.set(betriebsnummer, { name, betriebsnummer });
	}
}
for (const insurer of STATUTORY_HEALTH_INSURERS.insurers) {
	if (!fromFile.has(insurer.betriebsnummer)) {
		fromFile.set(insurer.betriebsnummer, { ...insurer, removedOn: insurer.removedOn ?? asOf });
	}
}

const insurers = [...fromFile.values()].sort(
	(a, b) => a.name.localeCompare(b.name, "de") || a.betriebsnummer.localeCompare(b.betriebsnummer),
);
const line = (insurer: StatutoryInsurer) => `\t\t${JSON.stringify(insurer)},`;

writeFileSync(
	TARGET,
	`/**
 * The statutory health insurers (gesetzliche Krankenkassen) an org admin picks
 * from, with the Betriebsnummer payroll reports to (spec #2068). Generated by
 * \`scripts/update-statutory-health-insurers.ts\`; do not edit by hand.
 *
 * Source: the GKV-Spitzenverband's Stammdatendatei (§§ 95b, 98a SGB IV),
 * file created ${created}, Einzugsstellen of kassenart 14–18 and 20,
 * name = Kurzbezeichnung. Terms of use:
 * https://download.gkv-ag.de/Content/Stammdatendatei_Nutzungsbedingungen.pdf
 *
 * \`removedOn\`: the insurer left the list that day (merged into \`successor\`,
 * or closed). It stays on the records that picked it and is refused for new picks.
 */
import type { StatutoryInsurerList } from "./health-insurance";

export const STATUTORY_HEALTH_INSURERS: StatutoryInsurerList = {
	source: ${JSON.stringify(SOURCE)},
	asOf: ${JSON.stringify(asOf)},
	insurers: [
${insurers.map(line).join("\n")}
	],
};
`,
);
console.log(
	`Wrote ${insurers.length} insurers (${insurers.filter((insurer) => !insurer.removedOn).length} current) as of ${asOf}`,
);

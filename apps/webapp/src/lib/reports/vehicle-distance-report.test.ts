import { Temporal } from "temporal-polyfill";
import { describe, expect, it } from "vitest";
import {
	buildVehicleDistanceReport,
	buildVehicleDistanceReportDocument,
	type VehicleDistanceVehicle,
	type VehicleDistanceWork,
} from "./vehicle-distance-report";

const van: VehicleDistanceVehicle = {
	kind: "organization",
	id: "vehicle-van",
	name: "Van",
	licencePlate: "B-VN 1",
	archived: false,
};
const audi: VehicleDistanceVehicle = {
	kind: "organization",
	id: "vehicle-audi",
	name: "Audi A4",
	licencePlate: "B-AU 4",
	archived: true,
};
const own: VehicleDistanceVehicle = { kind: "own" };

function work(
	employeeId: string,
	employeeName: string,
	vehicle: VehicleDistanceVehicle,
	day: string,
	distanceKm: number,
): VehicleDistanceWork {
	return { employeeId, employeeName, vehicle, workDay: Temporal.PlainDate.from(day), distanceKm };
}

const range = {
	fromDay: Temporal.PlainDate.from("2026-01-15"),
	toDay: Temporal.PlainDate.from("2026-03-10"),
};

describe("distance per vehicle report", () => {
	it("lists every month of the period, also months without driving", () => {
		const report = buildVehicleDistanceReport({ ...range, work: [] });

		expect(report.months).toEqual(["2026-01", "2026-02", "2026-03"]);
		expect(report.period).toEqual({ fromDay: "2026-01-15", toDay: "2026-03-10" });
		expect(report.vehicles).toEqual([]);
		expect(report.monthlyKm).toEqual([0, 0, 0]);
		expect(report.totalKm).toBe(0);
	});

	it("sums kilometres per vehicle, employee and month", () => {
		const report = buildVehicleDistanceReport({
			...range,
			work: [
				work("e-zoe", "Zoe", van, "2026-01-31", 40),
				work("e-zoe", "Zoe", van, "2026-02-01", 25),
				work("e-zoe", "Zoe", van, "2026-02-20", 5),
				work("e-ada", "Ada", van, "2026-03-02", 12),
				work("e-ada", "Ada", own, "2026-02-03", 30),
				work("e-zoe", "Zoe", own, "2026-03-09", 8),
				work("e-ada", "Ada", audi, "2026-01-20", 100),
			],
		});

		// Organization vehicles by name, then "own vehicle" last; employees by name.
		expect(report.vehicles).toEqual([
			{
				vehicle: audi,
				monthlyKm: [100, 0, 0],
				totalKm: 100,
				employees: [
					{ employeeId: "e-ada", employeeName: "Ada", monthlyKm: [100, 0, 0], totalKm: 100 },
				],
			},
			{
				vehicle: van,
				monthlyKm: [40, 30, 12],
				totalKm: 82,
				employees: [
					{ employeeId: "e-ada", employeeName: "Ada", monthlyKm: [0, 0, 12], totalKm: 12 },
					{ employeeId: "e-zoe", employeeName: "Zoe", monthlyKm: [40, 30, 0], totalKm: 70 },
				],
			},
			{
				vehicle: own,
				monthlyKm: [0, 30, 8],
				totalKm: 38,
				employees: [
					{ employeeId: "e-ada", employeeName: "Ada", monthlyKm: [0, 30, 0], totalKm: 30 },
					{ employeeId: "e-zoe", employeeName: "Zoe", monthlyKm: [0, 0, 8], totalKm: 8 },
				],
			},
		]);
		expect(report.monthlyKm).toEqual([140, 60, 20]);
		expect(report.totalKm).toBe(220);
	});

	it("groups every own vehicle into one row, whoever drove it", () => {
		const report = buildVehicleDistanceReport({
			...range,
			work: [work("e-1", "Ben", own, "2026-02-01", 10), work("e-2", "Cleo", own, "2026-02-02", 20)],
		});

		expect(report.vehicles).toHaveLength(1);
		expect(report.vehicles[0]).toMatchObject({ vehicle: { kind: "own" }, totalKm: 30 });
	});

	it("exports one row per vehicle and employee with kilometres per month", () => {
		const report = buildVehicleDistanceReport({
			...range,
			work: [
				work("e-zoe", "Zoe", van, "2026-01-31", 40),
				work("e-ada", "Ada", own, "2026-02-03", 30),
				work("e-ada", "Ada", audi, "2026-03-01", 100),
			],
		});

		const document = buildVehicleDistanceReportDocument(report, {
			labels: {
				title: "Distance per vehicle",
				period: "Period",
				generatedAt: "Generated on",
				table: "Kilometres",
				vehicle: "Vehicle",
				licencePlate: "Licence plate",
				employee: "Employee",
				total: "Total",
				ownVehicle: "Own vehicle",
				archived: "archived",
				note: "Whole kilometres by the month the work started in.",
				footer: "Generated by Z8",
				monthLabel: (month) => `M${month}`,
			},
			periodLabel: "15 Jan – 10 Mar 2026",
			generatedAt: "13 Oct 2026",
		});

		expect(document.title).toBe("Distance per vehicle");
		expect(document.facts).toEqual([
			{ label: "Period", value: "15 Jan – 10 Mar 2026" },
			{ label: "Generated on", value: "13 Oct 2026" },
		]);
		expect(document.tables).toEqual([
			{
				title: "Kilometres",
				columns: [
					{ key: "vehicle", header: "Vehicle", kind: "text" },
					{ key: "licencePlate", header: "Licence plate", kind: "text" },
					{ key: "employee", header: "Employee", kind: "text" },
					{ key: "2026-01", header: "M2026-01", kind: "count" },
					{ key: "2026-02", header: "M2026-02", kind: "count" },
					{ key: "2026-03", header: "M2026-03", kind: "count" },
					{ key: "total", header: "Total", kind: "count" },
				],
				rows: [
					["Audi A4 (archived)", "B-AU 4", "Ada", 0, 0, 100, 100],
					["Van", "B-VN 1", "Zoe", 40, 0, 0, 40],
					["Own vehicle", "", "Ada", 0, 30, 0, 30],
				],
				totals: ["Total", "", "", 40, 30, 100, 170],
			},
		]);
		expect(document.notes).toEqual(["Whole kilometres by the month the work started in."]);
		expect(document.footer).toBe("Generated by Z8 | 13 Oct 2026");
	});

	it("ignores work outside the period's months", () => {
		const report = buildVehicleDistanceReport({
			...range,
			work: [work("e-1", "Ben", van, "2025-12-31", 10), work("e-1", "Ben", van, "2026-04-01", 7)],
		});

		expect(report.vehicles).toEqual([]);
		expect(report.totalKm).toBe(0);
	});
});

/** The figures of one table row, whatever the row is (project, employee, customer). */
export interface ReportFigureRow {
	totalMinutes: number;
	workPeriodCount: number;
	billable?: BillableFigures;
}

export interface ReportFigureColumn extends ReportColumn {
	value(row: ReportFigureRow): ReportCell;
}

/** A group of figure columns derived from the rows it renders. */
export interface ReportFigureGroup {
	id: string;
	columns(
		rows: readonly ReportFigureRow[],
		context: ProjectReportExportContext & { currency: string | null },
	): ReportFigureColumn[];
}

const hours = (minutes: number) => Math.round((minutes / 60) * 100) / 100;

export const hoursFigureGroup: ReportFigureGroup = {
	id: "hours",
	columns: (_rows, { labels }) => [
		{ key: "hours", header: labels.hours, kind: "hours", value: (row) => hours(row.totalMinutes) },
		{
			key: "workPeriods",
			header: labels.workPeriods,
			kind: "count",
			value: (row) => row.workPeriodCount,
		},
	],
};

/** Billable Time figures; cost and margin only when the rows carry them. */
export const billableFigureGroup: ReportFigureGroup = {
	id: "billable",
	columns: (rows, { labels, currency }) => {
		if (!rows.some((row) => row.billable)) return [];
		const money = (label: string) => (currency ? `${label} (${currency})` : label);
		const figure = (read: (figures: BillableFigures) => ReportCell) => (row: ReportFigureRow) =>
			row.billable ? read(row.billable) : "";
		const columns: ReportFigureColumn[] = [
			{
				key: "billableHours",
				header: labels.billableHours,
				kind: "hours",
				value: figure((f) => hours(f.billableMinutes)),
			},
			{
				key: "nonBillableHours",
				header: labels.nonBillableHours,
				kind: "hours",
				value: figure((f) => hours(f.nonBillableMinutes)),
			},
			{
				key: "revenue",
				header: money(labels.revenue),
				kind: "money",
				value: figure((f) => f.revenue),
			},
			{
				key: "unpricedWork",
				header: labels.unpricedWork,
				kind: "count",
				value: figure((f) => f.unpricedWorkCount),
			},
			{
				key: "unpricedHours",
				header: labels.unpricedHours,
				kind: "hours",
				value: figure((f) => Math.round(f.unpricedHours * 100) / 100),
			},
			{
				key: "pendingReview",
				header: labels.pendingReview,
				kind: "count",
				value: figure((f) => f.pendingReviewCount),
			},
		];
		if (rows.some((row) => row.billable?.access === "full")) {
			const full = (read: (figures: Extract<BillableFigures, { access: "full" }>) => ReportCell) =>
				figure((f) => (f.access === "full" ? read(f) : ""));
			columns.push(
				{ key: "cost", header: money(labels.cost), kind: "money", value: full((f) => f.cost) },
				{
					key: "margin",
					header: money(labels.margin),
					kind: "money",
					value: full((f) => f.margin),
				},
				{
					key: "marginPercent",
					header: labels.marginPercent,
					kind: "percent",
					value: full((f) => f.marginPercent ?? (f.margin === null ? null : "")),
				},
			);
		}
		return columns;
	},
};


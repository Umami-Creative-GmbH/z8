/** The figure groups every project report and customer view export renders, in order. */
export const PROJECT_REPORT_FIGURE_GROUPS: readonly ReportFigureGroup[] = [
	hoursFigureGroup,
	billableFigureGroup,
	invoicingFigureGroup,
];

interface FigureTableInput<Row extends ReportFigureRow> {
	title: string;
	/** Leading text columns, such as the employee or the customer and project. */
	leading: { key: string; header: string; value: (row: Row) => string }[];
	rows: readonly Row[];
	totals?: { label: string; row: ReportFigureRow };
}

function figureTable<Row extends ReportFigureRow>(
	input: FigureTableInput<Row>,
	groups: readonly ReportFigureGroup[],
	context: ProjectReportExportContext & { currency: string | null },
): ReportTable {
	const figureRows: ReportFigureRow[] = [
		...input.rows,
		...(input.totals ? [input.totals.row] : []),
	];
	const figureColumns = groups.flatMap((group) => group.columns(figureRows, context));
	const columns: ReportColumn[] = [
		...input.leading.map(({ key, header }) => ({ key, header, kind: "text" as const })),
		...figureColumns.map(({ key, header, kind }) => ({ key, header, kind })),
	];
	return {
		title: input.title,
		columns,
		rows: input.rows.map((row) => [
			...input.leading.map((column) => column.value(row)),
			...figureColumns.map((column) => column.value(row)),
		]),
		...(input.totals
			? {
					totals: [
						input.totals.label,
						...input.leading.slice(1).map(() => ""),
						...figureColumns.map((column) => column.value(input.totals?.row as ReportFigureRow)),
					],
				}
			: {}),
	};
}

const dayOf = (isoInstant: string) => isoInstant.slice(0, 10);

function billableFacts(
	billableTime: BillableTimeReportContext | undefined,
	labels: ProjectReportExportLabels,
) {
	return billableTime
		? [
				{ label: labels.currency, value: billableTime.currency },
				{ label: labels.ratesResolvedAt, value: billableTime.ratesResolvedAt },
			]
		: [];
}

function billableNotes(
	rows: readonly ReportFigureRow[],
	labels: ProjectReportExportLabels,
): string[] {
	if (!rows.some((row) => row.billable)) return [];
	const notes = [labels.roundingNote, labels.ratesNote];
	if (rows.some((row) => row.billable?.invoicing)) notes.push(labels.invoicingNote);
	if (rows.some((row) => row.billable?.access === "full")) notes.push(labels.costUnknownNote);
	return notes;
}

/** The export document of one project's detailed report. */
export function buildProjectReportDocument(
	report: ProjectDetailedReport,
	context: ProjectReportExportContext,
	groups: readonly ReportFigureGroup[] = PROJECT_REPORT_FIGURE_GROUPS,
): ReportDocument {
	const { labels } = context;
	const tableContext = { ...context, currency: report.billableTime?.currency ?? null };
	const summaryRow: ReportFigureRow & { name: string } = {
		name: report.project.name,
		totalMinutes: report.summary.totalMinutes,
		workPeriodCount: report.summary.workPeriodCount,
		billable: report.summary.billable,
	};
	return {
		title: `${labels.projectReportTitle} – ${report.project.name}`,
		facts: [
			{ label: labels.project, value: report.project.name },
			...(report.project.customer
				? [{ label: labels.customer, value: report.project.customer.name }]
				: []),
			{
				label: labels.period,
				value: `${dayOf(report.period.startDate)} – ${dayOf(report.period.endDate)}`,
			},
			{ label: labels.generatedAt, value: context.generatedAt },
			...billableFacts(report.billableTime, labels),
		],
		tables: [
			figureTable(
				{
					title: labels.summaryTable,
					leading: [{ key: "project", header: labels.project, value: (row) => row.name }],
					rows: [summaryRow],
				},
				groups,
				tableContext,
			),
			figureTable(
				{
					title: labels.employeesTable,
					leading: [{ key: "employee", header: labels.employee, value: (row) => row.employeeName }],
					rows: report.employeeBreakdown,
					totals: { label: labels.total, row: summaryRow },
				},
				groups,
				tableContext,
			),
			{
				title: labels.dailyHoursTable,
				columns: [
					{ key: "date", header: labels.date, kind: "text" },
					{ key: "hours", header: labels.hours, kind: "hours" },
				],
				rows: report.timeSeries.map((point) => [point.date, Math.round(point.hours * 100) / 100]),
			},
		],
		notes: billableNotes([summaryRow], labels),
		unknownLabel: labels.costUnknown,
		fileStem: `project-report-${report.project.name}`,
		footer: `${labels.footer} | ${context.generatedAt}`,
	};
}

/** The export document of the customer view. */
export function buildCustomerReportDocument(
	view: CustomerBillableReport,
	context: ProjectReportExportContext,
	groups: readonly ReportFigureGroup[] = PROJECT_REPORT_FIGURE_GROUPS,
): ReportDocument {
	const { labels } = context;
	const tableContext = { ...context, currency: view.billableTime.currency };
	const projects = view.customers.flatMap((row) =>
		row.projects.map((project) => ({ ...project, customerName: row.customer.name })),
	);
	return {
		title: labels.customerReportTitle,
		facts: [
			{
				label: labels.period,
				value: `${dayOf(view.period.startDate)} – ${dayOf(view.period.endDate)}`,
			},
			{ label: labels.generatedAt, value: context.generatedAt },
			...billableFacts(view.billableTime, labels),
		],
		tables: [
			figureTable(
				{
					title: labels.customersTable,
					leading: [
						{ key: "customer", header: labels.customer, value: (row) => row.customer.name },
					],
					rows: view.customers,
					totals: { label: labels.total, row: view.totals },
				},
				groups,
				tableContext,
			),
			figureTable(
				{
					title: labels.projectsTable,
					leading: [
						{ key: "customer", header: labels.customer, value: (row) => row.customerName },
						{ key: "project", header: labels.project, value: (row) => row.project.name },
					],
					rows: projects,
				},
				groups,
				tableContext,
			),
		],
		notes: billableNotes([view.totals], labels),
		unknownLabel: labels.costUnknown,
		fileStem: "customer-report",
		footer: `${labels.footer} | ${context.generatedAt}`,
	};
}

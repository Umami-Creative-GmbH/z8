/**
 * Project report and customer view exports (#902): builds the format-neutral
 * report document that the CSV, Excel and PDF exporters render
 * (`exporters/report-document*.ts`). Client-safe.
 *
 * Exports only ever contain what the report data contains: cost and margin
 * are stripped at the data layer for project managers
 * (`lib/billable-time/report-figures.ts`), so their columns cannot appear.
 *
 * Figure groups are the seam for more figures: each group contributes columns
 * to every figure table (summary, employees, customers, projects) from the
 * rows' data. Hours and Billable Time figures are the groups today; invoiced
 * and un-invoiced figures (#903) are another group that reads its own optional
 * key on the same rows. Pass a longer group list, or append to
 * `PROJECT_REPORT_FIGURE_GROUPS`, without touching the exporters.
 */


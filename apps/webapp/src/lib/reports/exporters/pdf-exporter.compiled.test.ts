import { randomUUID } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { Temporal } from "temporal-polyfill";
import { expect, it } from "vitest";
import type { ReportData } from "../types";

it("exports employee report content as a real PDF after React Compiler optimization", async () => {
	const require = createRequire(import.meta.url);
	const babel = require("next/dist/compiled/babel/core");
	const compiler = require("babel-plugin-react-compiler");
	const esbuild = createRequire(require.resolve("tsx/package.json"))("esbuild");
	const filename = fileURLToPath(new URL("./pdf-exporter.tsx", import.meta.url));
	const compiled = babel.transformSync(readFileSync(filename, "utf8"), {
		filename,
		configFile: false,
		babelrc: false,
		parserOpts: { plugins: ["typescript", "jsx"] },
		plugins: [[compiler, { target: "19" }]],
	});
	const bundled = await esbuild.build({
		stdin: { contents: compiled.code, loader: "tsx", resolveDir: dirname(filename) },
		bundle: true,
		platform: "node",
		format: "esm",
		packages: "external",
		jsx: "automatic",
		write: false,
	});
	const directory = resolve(".tmp/compiled-employee-report-pdf");
	mkdirSync(directory, { recursive: true });
	const output = resolve(directory, `${randomUUID()}.mjs`);
	writeFileSync(output, bundled.outputFiles[0].text);
	const module = await import(/* @vite-ignore */ pathToFileURL(output).href);
	const report: ReportData = {
		employee: {
			id: "synthetic-worker",
			name: "Synthetic Worker",
			employeeNumber: "SYN-7",
			position: "Analyst",
			email: "worker@example.test",
			contractType: "fixed",
			customFields: [{ fieldId: "reference", name: "Reference", type: "text", value: "PO-42" }],
		},
		period: { startDate: "2025-01-01", endDate: "2025-12-31", label: "Year 2025" },
		workHours: {
			totalHours: 2088,
			totalMinutes: 125280,
			workDays: 261,
			averagePerDay: 8,
			byMonth: new Map([
				["2025-01", { hours: 184, days: 23 }],
				["2025-02", { hours: 160, days: 20 }],
				["2025-03", { hours: 168, days: 21 }],
				["2025-04", { hours: 176, days: 22 }],
				["2025-05", { hours: 176, days: 22 }],
				["2025-06", { hours: 168, days: 21 }],
				["2025-07", { hours: 184, days: 23 }],
				["2025-08", { hours: 168, days: 21 }],
				["2025-09", { hours: 176, days: 22 }],
				["2025-10", { hours: 184, days: 23 }],
				["2025-11", { hours: 160, days: 20 }],
				["2025-12", { hours: 184, days: 23 }],
			]),
		},
		absences: {
			totalDays: 2,
			byCategory: new Map(),
			vacation: { approved: 1, pending: 0 },
			sick: { approved: 1, pending: 0 },
			homeOffice: {
				days: 52,
				hoursWorked: 416,
				dateDetails: Array.from({ length: 52 }, (_, weeks) => ({
					date: Temporal.PlainDate.from("2025-01-03").add({ weeks }).toString(),
					hours: 8,
				})),
			},
			other: { approved: 0, pending: 0 },
		},
		complianceMetrics: { attendancePercentage: 100, overtimeMinutes: 60, underTimeMinutes: 0 },
	};
	const bytes = await module.exportToPDF(report, {
		generatedAt: "2026-11-16T12:00:00Z",
		locale: "en-US",
		timezone: "UTC",
		timeFormat: "24h",
	});
	expect(new TextDecoder().decode(bytes.slice(0, 5))).toBe("%PDF-");
	const { getDocument } = await import("pdfjs-dist/legacy/build/pdf.mjs");
	const task = getDocument({ data: bytes, useSystemFonts: true });
	try {
		const pdf = await task.promise;
		const pages: string[] = [];
		for (let number = 1; number <= pdf.numPages; number++) {
			const content = await (await pdf.getPage(number)).getTextContent();
			pages.push(content.items.map((item) => ("str" in item ? item.str : "")).join(" "));
		}
		const text = pages.join(" ");
		for (const value of [
			"Employee Report",
			"Synthetic Worker",
			"SYN-7",
			"Year 2025",
			"2088h",
			"261",
			"2025-01",
			"2025-12",
			"184h",
			"PO-42",
			"416h",
			"2025-01-03",
			"2025-12-26",
			"12:00",
			"Generated by Z8 Time Tracking",
		]) {
			expect(text).toContain(value);
		}
		expect(text).not.toContain("EARNINGS SUMMARY");
	} finally {
		await task.destroy();
	}
	const hourlyBytes = await module.exportToPDF(
		{
			...report,
			employee: { ...report.employee, contractType: "hourly", customFields: [] },
			hourlyEarnings: {
				totalHours: 16,
				totalEarnings: 360,
				currency: "EUR",
				byRatePeriod: [
					{
						rate: 20,
						currency: "EUR",
						periodStart: "2025-01-01",
						periodEnd: "2025-06-30",
						hours: 8,
						earnings: 160,
					},
					{
						rate: 25,
						currency: "EUR",
						periodStart: "2025-07-01",
						periodEnd: "2025-12-31",
						hours: 8,
						earnings: 200,
					},
				],
			},
		},
		{
			generatedAt: "2026-11-16T12:00:00Z",
			locale: "en-US",
			timezone: "Asia/Tokyo",
			timeFormat: "24h",
		},
	);
	const hourlyTask = getDocument({ data: hourlyBytes, useSystemFonts: true });
	try {
		const pdf = await hourlyTask.promise;
		const pages: string[] = [];
		for (let number = 1; number <= pdf.numPages; number++) {
			const content = await (await pdf.getPage(number)).getTextContent();
			pages.push(content.items.map((item) => ("str" in item ? item.str : "")).join(" "));
		}
		const text = pages.join(" ");
		expect(text).toContain("EARNINGS SUMMARY (HOURLY TERMS)");
		expect(text).toContain("2025-06-30");
		expect(text).toContain("2025-07-01");
		expect(text).toContain("20,00");
		expect(text).toContain("25,00");
		expect(text).toContain("360,00");
		expect(text).toContain("21:00");
		expect(text).not.toContain("Custom Fields");
		expect(text).not.toContain("PO-42");
	} finally {
		await hourlyTask.destroy();
	}
}, 30_000);

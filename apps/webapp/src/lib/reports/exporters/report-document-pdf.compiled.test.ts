import { randomUUID } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { expect, it } from "vitest";
import {
	buildTimesheetDocument,
	DEFAULT_TIMESHEET_LABELS,
} from "@/lib/billable-time/hand-off/timesheet-document";
import { buildSharedSnapshotDocument } from "@/lib/projects/report-share/shared-snapshot-document";
import { DEFAULT_PROJECT_REPORT_EXPORT_LABELS } from "@/lib/reports/project-report-export";
import { buildVehicleDistanceReportDocument } from "@/lib/reports/vehicle-distance-report";
import type { ReportDocument } from "./report-document";

/** Exercise the same compiler boundary as Next, then the real PDF renderer. No PDF primitives are mocked. */
it("renders report facts, table rows, unknown values and notes after React Compiler optimization", async () => {
	const require = createRequire(import.meta.url);
	const babel = require("next/dist/compiled/babel/core");
	const compiler = require("babel-plugin-react-compiler");
	const esbuild = createRequire(require.resolve("tsx/package.json"))("esbuild");
	const filename = fileURLToPath(new URL("./report-document-pdf.tsx", import.meta.url));
	const compiled = babel.transformSync(readFileSync(filename, "utf8"), {
		filename,
		configFile: false,
		babelrc: false,
		parserOpts: { plugins: ["typescript", "jsx"] },
		plugins: [[compiler, { target: "19" }]],
	});
	const bundled = await esbuild.build({
		stdin: {
			contents: compiled.code,
			loader: "tsx",
			resolveDir: dirname(filename),
		},
		bundle: true,
		platform: "node",
		format: "esm",
		packages: "external",
		jsx: "automatic",
		write: false,
	});
	const directory = resolve(".tmp/compiled-report-pdf");
	mkdirSync(directory, { recursive: true });
	const output = resolve(directory, `${randomUUID()}.mjs`);
	writeFileSync(output, bundled.outputFiles[0].text);
	const module = await import(/* @vite-ignore */ pathToFileURL(output).href);
	const document: ReportDocument = {
		title: "Synthetic project report",
		fileStem: "synthetic-project",
		facts: [{ label: "Period", value: "2026-11-01 to 2026-11-30" }],
		tables: [
			{
				title: "Summary",
				columns: [
					{ key: "project", header: "Project", kind: "text" },
					{ key: "hours", header: "Hours", kind: "hours" },
					{ key: "margin", header: "Margin", kind: "money" },
				],
				rows: [["Synthetic Delivery", 5, null]],
				totals: ["Total", 5, null],
			},
		],
		notes: ["Cost unknown remains unavailable."],
		unknownLabel: "Cost unknown",
		footer: "Generated by Z8",
	};
	const bytes = await module.exportReportDocumentToPDF(document);
	expect(new TextDecoder().decode(bytes.slice(0, 5))).toBe("%PDF-");
	const { getDocument } = await import("pdfjs-dist/legacy/build/pdf.mjs");
	const task = getDocument({ data: bytes, useSystemFonts: true });
	const pdf = await task.promise;
	const page = await pdf.getPage(1);
	const content = await page.getTextContent();
	const text = content.items.map((item) => ("str" in item ? item.str : "")).join(" ");
	expect(text).toContain("Synthetic project report");
	expect(text).toContain("2026-11-01 to 2026-11-30");
	expect(text).toContain("Synthetic Delivery");
	expect(text).toContain("5.00");
	expect(text).toContain("Cost unknown remains unavailable.");
	expect(text).toContain("Generated by Z8");
	await task.destroy();
	const context = {
		labels: DEFAULT_PROJECT_REPORT_EXPORT_LABELS,
		generatedAt: "2026-11-10 10:00",
	};
	const documents = [
		{
			document: buildTimesheetDocument(
				{
					customerName: "Synthetic customer",
					period: { from: "2026-11-01", to: "2026-11-30" },
					timesheet: [
						{
							day: "2026-11-10",
							employeeName: "Synthetic worker",
							projectName: "Synthetic Delivery",
							start: "08:00",
							end: "13:00",
							hours: "5.00",
						},
					],
				},
				{ labels: DEFAULT_TIMESHEET_LABELS, generatedAt: context.generatedAt },
			),
			expected: ["Synthetic worker", "08:00", "13:00", "5.00"],
		},
		{
			document: buildVehicleDistanceReportDocument(
				{
					period: { fromDay: "2026-11-01", toDay: "2026-11-30" },
					months: ["2026-11"],
					vehicles: [
						{
							vehicle: { kind: "own" },
							totalKm: 42,
							monthlyKm: [42],
							employees: [
								{
									employeeId: "synthetic",
									employeeName: "Synthetic driver",
									totalKm: 42,
									monthlyKm: [42],
								},
							],
						},
					],
					totalKm: 42,
					monthlyKm: [42],
				},
				{
					generatedAt: context.generatedAt,
					periodLabel: "November 2026",
					labels: {
						title: "Vehicle distance",
						period: "Period",
						generatedAt: "Generated",
						table: "Distance",
						vehicle: "Vehicle",
						licencePlate: "Plate",
						employee: "Employee",
						total: "Total",
						ownVehicle: "Own vehicle",
						archived: "Archived",
						note: "Recorded distance",
						footer: "Z8",
						monthLabel: (month) => month,
					},
				},
			),
			expected: ["Synthetic driver", "Own vehicle", "42"],
		},
		{
			document: buildSharedSnapshotDocument(
				{
					kind: "project",
					project: { name: "Frozen project", customer: null },
					period: { startDate: "2026-11-01", endDate: "2026-11-30" },
					summary: { totalMinutes: 300, workPeriodCount: 2 },
					employeeBreakdown: [],
					timeSeries: [],
				},
				context,
			),
			expected: ["Frozen project", "5.00"],
		},
		{
			document: buildSharedSnapshotDocument(
				{
					kind: "customer",
					period: { startDate: "2026-11-01", endDate: "2026-11-30" },
					customer: {
						customer: { name: "Frozen customer" },
						totalMinutes: 300,
						workPeriodCount: 2,
						projects: [
							{
								project: { name: "Frozen project" },
								totalMinutes: 300,
								workPeriodCount: 2,
							},
						],
					},
				},
				context,
			),
			expected: ["Frozen customer", "Frozen project", "5.00"],
		},
		{
			document: {
				...document,
				tables: [
					{
						...document.tables[0],
						rows: Array.from({ length: 80 }, (_, index) => [`Record ${index + 1}`, 5, null]),
					},
				],
			},
			expected: ["Record 1", "Record 80", "Generated by Z8"],
		},
	];
	for (const fixture of documents) {
		const generated = await module.exportReportDocumentToPDF(fixture.document);
		const loading = getDocument({ data: generated, useSystemFonts: true });
		const parsed = await loading.promise;
		const pages: string[] = [];
		for (let number = 1; number <= parsed.numPages; number++) {
			const pageContent = await (await parsed.getPage(number)).getTextContent();
			pages.push(pageContent.items.map((item) => ("str" in item ? item.str : "")).join(" "));
		}
		for (const expected of fixture.expected) expect(pages.join(" ")).toContain(expected);
		if (fixture.document.title.includes("Frozen")) {
			expect(pages.join(" ")).not.toContain("Margin");
			expect(pages.join(" ")).not.toContain("Cost unknown");
		}
		await loading.destroy();
	}
}, 30_000);

/**
 * The summary page: period, totals, blockers and each employee's worked hours and
 * absence totals, all from the period read's Overview summary.
 */
export const summarySection: PayrollPdfSection = (context) => {
	const { Page, Text, View } = context.kit;
	const { read, t, format } = context;
	const summary = read.summary;
	const employees = [...summary.employees].sort(
		(left, right) => left.name.localeCompare(right.name) || compareText(left.id, right.id),
	);
	const employeeNames = new Map(employees.map((employee) => [employee.id, employee.name]));

	return [
		<Page key="summary" size="A4" style={basePageStyle}>
			<View style={styles.header}>
				<Text style={styles.kicker}>{t("payroll.pdf.summary.kicker", "Payroll export audit")}</Text>
				<Text style={styles.title}>{summary.organizationName}</Text>
				<View style={styles.headerGrid}>
					<View style={styles.headerItem}>
						<Text style={styles.label}>{t("payroll.pdf.summary.period", "Period")}</Text>
						<Text style={styles.value}>
							{`${summary.period.label} (${format.date(summary.period.start)} – ${format.date(summary.period.end)})`}
						</Text>
					</View>
					<View style={styles.headerItem}>
						<Text style={styles.label}>{t("payroll.pdf.summary.generated", "Generated")}</Text>
						<Text style={styles.value}>{format.instantUtc(summary.generatedAt)}</Text>
					</View>
					<View style={styles.headerItem}>
						<Text style={styles.label}>{t("payroll.pdf.summary.generatedBy", "Generated by")}</Text>
						<Text style={styles.value}>{summary.generatedBy.name}</Text>
					</View>
					<View style={styles.headerItem}>
						<Text style={styles.label}>{t("payroll.pdf.summary.exportScope", "Export scope")}</Text>
						<Text style={styles.value}>
							{t("payroll.pdf.summary.combinedSummary", "Combined payroll summary")}
						</Text>
					</View>
				</View>
			</View>

			<View style={styles.metrics}>
				<View style={styles.metricCard}>
					<Text style={styles.label}>{t("payroll.pdf.summary.employees", "Employees")}</Text>
					<Text style={styles.metricValue}>{summary.totals.employeeCount}</Text>
				</View>
				<View style={styles.metricCard}>
					<Text style={styles.label}>{t("payroll.pdf.summary.workedHours", "Worked hours")}</Text>
					<Text style={styles.metricValue}>
						{format.hoursValue(summary.totals.totalWorkedHours)}
					</Text>
				</View>
				<View style={[styles.metricCard, styles.metricCardLast]}>
					<Text style={styles.label}>{t("payroll.pdf.summary.blockers", "Blockers")}</Text>
					<Text style={styles.metricValue}>{summary.totals.blockerCount}</Text>
				</View>
			</View>

			{summary.blockers.length > 0 ? (
				<View style={styles.blockerBand}>
					<Text style={styles.blockerTitle}>
						{t("payroll.pdf.summary.blockerReview", "Blocker review required")}
					</Text>
					{summary.blockers.map((blocker) => (
						<Text key={payrollBlockerIdentity(blocker)} style={styles.blockerText}>
							{blockerLine(context, blocker, employeeNames)}
						</Text>
					))}
				</View>
			) : null}

			<Text style={styles.sectionTitle}>
				{t("payroll.pdf.summary.employeeTotals", "Employee totals")}
			</Text>
			<View style={styles.table}>
				<View style={styles.tableHeader} fixed>
					<Text style={[styles.cell, styles.employeeCell]}>
						{t("payroll.pdf.summary.employee", "Employee")}
					</Text>
					<Text style={[styles.cell, styles.teamCell]}>
						{t("payroll.pdf.summary.team", "Team")}
					</Text>
					<Text style={[styles.cell, styles.contractCell]}>
						{t("payroll.pdf.summary.contract", "Contract")}
					</Text>
					<Text style={[styles.cell, styles.hoursCell]}>
						{t("payroll.pdf.summary.hours", "Hours")}
					</Text>
					<Text style={[styles.cell, styles.absenceCell]}>
						{t("payroll.pdf.summary.absenceTotals", "Absence totals")}
					</Text>
					<Text style={[styles.cell, styles.statusCell]}>
						{t("payroll.pdf.summary.status", "Status")}
					</Text>
				</View>
				{employees.map((employee) => (
					<View
						key={employee.id}
						style={
							employee.hasBlockers ? [styles.tableRow, styles.tableRowBlocked] : styles.tableRow
						}
						wrap={false}
					>
						<View style={[styles.cell, styles.employeeCell]}>
							<Text style={styles.employeeName}>{employee.name}</Text>
							<Text style={styles.muted}>
								{employee.employeeNumber ?? t("payroll.pdf.noEmployeeNumber", "No employee no.")}
							</Text>
						</View>
						<Text style={[styles.cell, styles.teamCell]}>
							{employee.teamName ?? t("payroll.pdf.noTeam", "No team")}
						</Text>
						<Text style={[styles.cell, styles.contractCell]}>
							{employee.contractType === "hourly"
								? t("payroll.pdf.summary.contractHourly", "Hourly")
								: t("payroll.pdf.summary.contractFixed", "Fixed")}
						</Text>
						<Text style={[styles.cell, styles.hoursCell]}>
							{format.hoursValue(employee.workedHours)}
						</Text>
						<Text style={[styles.cell, styles.absenceCell]}>
							{absenceTotals(context, employee)}
						</Text>
						<Text style={[styles.cell, styles.statusCell]}>
							{employee.hasBlockers
								? t("payroll.pdf.summary.statusReview", "Review")
								: t("payroll.pdf.summary.statusClear", "Clear")}
						</Text>
					</View>
				))}
			</View>

			<Text style={styles.auditNote}>
				{t(
					"payroll.pdf.summary.auditNote",
					"Audit note: Blockers are informational review markers and did not prevent this export. Confirm unresolved items before payroll submission.",
				)}
			</Text>
			<PayrollPdfFooter context={context} />
		</Page>,
	];
};

/** "Anna Berg · +1.5 h since settled · 3.11.2026, 09:00" */
function blockerLine(
	context: PayrollPdfContext,
	blocker: PayrollBlocker,
	employeeNames: ReadonlyMap<string, string>,
): string {
	const { t, locale, format } = context;
	const date = blocker.date
		? [format.date(blocker.date), blocker.time].filter(Boolean).join(", ")
		: null;
	return [
		employeeNames.get(blocker.employeeId) ??
			t("payroll.blockers.unknownEmployee", "Unknown employee"),
		payrollBlockerTypeLabel(blocker, locale, t),
		date,
	]
		.filter(Boolean)
		.join(" · ");
}

function absenceTotals(context: PayrollPdfContext, employee: PayrollEmployeeSummary): string {
	const { t, format } = context;
	if (employee.absenceDaysByCategory.length === 0) {
		return t("payroll.pdf.summary.noAbsences", "None");
	}
	return employee.absenceDaysByCategory
		.map((absence) =>
			t("payroll.pdf.summary.absenceCategoryDays", "{category}: {days} d", {
				category: absence.categoryName,
				days: format.days(absence.days),
			}),
		)
		.join("; ");
}

function compareText(left: string, right: string): number {
	if (left < right) return -1;
	if (left > right) return 1;
	return 0;
}
